// =====================
// LANGUAGE SYSTEM
// =====================
let currentLang = 'th';
try { currentLang = localStorage.getItem('coremod-lang') || 'th'; } catch (e) {}

function applyLang(lang) {
  const dict = T[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  // Button shows the language you switch to
  document.getElementById('langBtn').textContent = lang === 'en' ? 'TH' : 'EN';

  document.documentElement.lang = lang;
  try { localStorage.setItem('coremod-lang', lang); } catch (e) {}
  currentLang = lang;
}

function toggleLang() {
  applyLang(currentLang === 'en' ? 'th' : 'en');
}

// =====================
// TERMINAL BOOT (hero)
// =====================
const BOOT_LINES = [
  '$ coremod --status',
  '> repair ........... [OK]',
  '> custom builds .... [OK]',
  '> remote support ... [OK]',
];

let lineIdx = 0;
let charIdx = 0;
const LINE_IDS = ['t1', 't2', 't3', 't4'];

function typeNext() {
  if (lineIdx >= LINE_IDS.length) return;
  const el = document.getElementById(LINE_IDS[lineIdx]);
  if (!el) return;
  const line = BOOT_LINES[lineIdx];
  if (charIdx < line.length) {
    el.textContent += line[charIdx];
    charIdx++;
    setTimeout(typeNext, 32);
  } else {
    lineIdx++;
    charIdx = 0;
    setTimeout(typeNext, 180);
  }
}

function showBootInstantly() {
  LINE_IDS.forEach((id, i) => {
    const el = document.getElementById(id);
    if (el) el.textContent = BOOT_LINES[i];
  });
}

// =====================
// NAV
// =====================
function toggleNav() {
  document.getElementById('navLinks').classList.toggle('open');
}

document.querySelectorAll('.nav-links a').forEach(a => {
  a.addEventListener('click', () => {
    document.getElementById('navLinks').classList.remove('open');
  });
});

const sections = document.querySelectorAll('section[id]');

function updateNav() {
  let current = '';
  sections.forEach(sec => {
    if (window.scrollY >= sec.offsetTop - 90) current = sec.id;
  });
  if (!current) return;
  document.querySelectorAll('.nav-links a').forEach(a => {
    a.classList.toggle('active', a.getAttribute('href') === '#' + current);
  });
}

// =====================
// SCROLL TO TOP
// =====================
function scrollToTop() {
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

window.addEventListener('scroll', () => {
  updateNav();
  document.getElementById('scrollTop').classList.toggle('show', window.scrollY > 400);
}, { passive: true });

// =====================
// FADE-IN
// =====================
const io = new IntersectionObserver((entries) => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.classList.add('visible');
      io.unobserve(e.target);
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll('.fade-in').forEach(el => io.observe(el));

// =====================
// CONTACT FORM
// =====================
const form       = document.getElementById('contactForm');
const submitBtn  = document.getElementById('submitBtn');
const formStatus = document.getElementById('formStatus');

if (form) form.addEventListener('submit', async (e) => {
  e.preventDefault();

  submitBtn.textContent = T[currentLang]['form-sending'];
  submitBtn.disabled = true;
  formStatus.textContent = '';
  formStatus.className = 'form-status';

  try {
    const res  = await fetch('https://api.web3forms.com/submit', {
      method: 'POST',
      body: new FormData(form),
    });
    const json = await res.json();
    if (!json.success) throw new Error(json.message || 'Submission failed.');

    formStatus.textContent = T[currentLang]['form-ok'];
    formStatus.classList.add('success');
    form.reset();
  } catch (err) {
    formStatus.textContent = T[currentLang]['form-err'];
    formStatus.classList.add('error');
  }

  submitBtn.textContent = T[currentLang]['form-submit'];
  submitBtn.disabled = false;
});

